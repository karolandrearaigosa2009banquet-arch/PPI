create policy "Users can read permitted pqrs" on public.pqrs for select to authenticated using ((select auth.uid()) = user_id or (select public.is_admin()));
create policy "Users can create own pqrs" on public.pqrs for insert to authenticated with check ((select auth.uid()) = user_id and estado = 'Enviado' and respuesta is null);
create policy "Admins can respond to pqrs" on public.pqrs for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

create index if not exists pqrs_user_created_idx on public.pqrs (user_id, created_at desc);
