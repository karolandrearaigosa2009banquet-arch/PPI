create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (user_id, full_name, email, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', 'Usuario'), new.email, 'usuario')
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists crear_perfil_al_registrar on auth.users;
drop trigger if exists on_auth_user_created on auth.users;
drop function if exists public.crear_perfil_usuario();
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql security definer stable set search_path = public as $$
  select exists (select 1 from public.profiles where user_id = (select auth.uid()) and role = 'admin');
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;
revoke all on table public.profiles, public.pqrs from anon, authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update on public.pqrs to authenticated;
alter table public.profiles enable row level security;
alter table public.pqrs enable row level security;

drop policy if exists "Users can view their own profile" on public.profiles;
