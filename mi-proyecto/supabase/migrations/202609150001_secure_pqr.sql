create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  phone text,
  address text,
  document_type text,
  document_number text,
  role text not null default 'usuario' check (role in ('usuario', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pqrs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  phone text,
  document_type text,
  document_number text,
  tipo text not null check (tipo in ('Petición', 'Queja', 'Reclamo')),
  mensaje text not null check (char_length(mensaje) between 10 and 2000),
  respuesta text check (respuesta is null or char_length(respuesta) <= 4000),
  estado text not null default 'Enviado' check (estado in ('Enviado', 'Respondido')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

